class SettingsStore(Protocol):
    def value(self, key: str, default: Any = None) -> Any: ...

    def setValue(self, key: str, value: Any) -> None: ...  # noqa: N802

    def sync(self) -> None: ...


def normalize_language(value: Any) -> str | None:
    if value is None:
        return None
    language = str(value).strip().lower().replace("-", "_")
    prefix = language.split("_", 1)[0]
    return prefix if prefix in SUPPORTED_LANGUAGES else None


def detect_system_language(locale_name: str | None) -> str:
    return "zh" if normalize_language(locale_name) == "zh" else "en"


def resolve_initial_language(saved: Any, locale_name: str | None) -> str:
    return normalize_language(saved) or detect_system_language(locale_name)


class LanguageManager:
    def __init__(
        self,
        settings: SettingsStore | None = None,
        system_locale_name: str | None = None,
    ) -> None:
        if settings is None or system_locale_name is None:
            from PySide6.QtCore import QLocale, QSettings

            settings = settings or QSettings()
            system_locale_name = system_locale_name or QLocale.system().name()

        self._settings = settings
        saved = settings.value(LANGUAGE_SETTING_KEY, None)
        self.language = resolve_initial_language(saved, system_locale_name)
        self._persist()

    def text(self, key: str, **values: Any) -> str:
        fallback = TRANSLATIONS["en"].get(key, key)
        template = TRANSLATIONS[self.language].get(key, fallback)
        return template.format(**values) if values else template

    def set_language(self, language: str) -> bool:
        normalized = normalize_language(language)
        if normalized is None:
            raise ValueError(f"Unsupported interface language: {language}")
        changed = normalized != self.language
        self.language = normalized
        self._persist()
        return changed

    def _persist(self) -> None:
        self._settings.setValue(LANGUAGE_SETTING_KEY, self.language)
        self._settings.sync()
